def main(apply: bool = True) -> int:
    d = json.loads(IFACE.read_text(encoding="utf-8"), object_pairs_hook=OrderedDict)

    names = [t["name"] for t in d["task"]]
    missing = set(names) - set(DESCRIPTIONS)
    extra = set(DESCRIPTIONS) - set(names)
    if missing or extra:
        print("任务与文案不匹配：")
        if missing:
            print("  缺文案:", missing)
        if extra:
            print("  多余文案:", extra)
        return 1

    new_tasks = []
    for t in d["task"]:
        name = t["name"]
        out = OrderedDict()
        for k, v in t.items():
            if k in ("doc", "description"):
                continue
            out[k] = v
            if k == "option":
                out["description"] = DESCRIPTIONS[name]
        if "description" not in out:
            out["description"] = DESCRIPTIONS[name]
        new_tasks.append(out)

    d["task"] = new_tasks

    if not apply:
        print(f"[dry-run] {len(new_tasks)} 个任务文案已就绪，未写入")
        return 0

    bak = ROOT / "backup" / f"interface.json.bak-{time.strftime('%Y%m%d-%H%M%S')}"
    shutil.copy2(IFACE, bak)
    IFACE.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    total = sum(len(v) for v in DESCRIPTIONS.values())
    print(f"已写入 {len(new_tasks)} 段 description（共 {total} 字，备份 {bak.name}）")
    return 0


if __name__ == "__main__":
    sys.exit(main(apply="--dry-run" not in sys.argv))
